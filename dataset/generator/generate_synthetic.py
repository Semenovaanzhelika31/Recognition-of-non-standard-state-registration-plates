#!/usr/bin/env python3
"""Генератор синтетической части датасета.

Пример (воспроизводит датасет бит-в-бит при том же seed и версиях библиотек):
    python generate_synthetic.py --out .. --n 5000 --seed 20261014

Каждое изображение i строится из независимого генератора
numpy.random.SeedSequence([seed, i]) — результат не зависит от числа процессов.
Пишет:
    <out>/images/synthetic/syn_XXXXX.jpg
    <out>/labels/syn_XXXXX.txt    # по строке на знак: cls cx cy w h x1 y1 x2 y2 x3 y3 x4 y4 (норм. 0..1)
    <out>/meta.csv                # разделитель ';', одна строка на знак
cls: 0 type1, 1 type1a, 2 type1b, 3 other.
"""
import argparse
import csv
import os
import sys
from multiprocessing import Pool

import cv2
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import scenes as sc  # noqa: E402

CLS = {"type1": 0, "type1a": 1, "type1b": 2, "other": 3}
SIZES = [(640, 480), (800, 600), (960, 540), (1280, 720)]
SIZE_P = [0.40, 0.25, 0.20, 0.15]
META_FIELDS = ["image", "plate_num", "plate_type", "bbox", "quad", "is_vehicle", "is_synthetic",
               "source", "license", "conditions"]


def build_one(args):
    idx, seed, out = args
    rng = np.random.default_rng(np.random.SeedSequence([seed, idx]))
    W, H = SIZES[rng.choice(len(SIZES), p=SIZE_P)]
    img, plates = sc.make_scene(rng, W, H)
    name = f"syn_{idx:05d}"
    q = int(rng.integers(60, 96))
    cv2.imwrite(os.path.join(out, "images", "synthetic", name + ".jpg"), img,
                [cv2.IMWRITE_JPEG_QUALITY, q])
    lab, rows = [], []
    for p in plates:
        quad = np.clip(p["quad"], 0, [W - 1, H - 1])
        x0, y0 = quad.min(0); x1, y1 = quad.max(0)
        lab.append("%d %.6f %.6f %.6f %.6f " % (CLS[p["type"]], (x0 + x1) / 2 / W, (y0 + y1) / 2 / H,
                                              (x1 - x0) / W, (y1 - y0) / H)
                   + " ".join("%.6f" % v for v in (quad / [W, H]).reshape(-1)))
        rows.append({
            "image": f"images/synthetic/{name}.jpg",
            "plate_num": p["text"] if p["type"] != "other" else "#",
            "plate_type": p["type"],
            "bbox": "%d,%d,%d,%d" % (round(x0), round(y0), round(x1 - x0), round(y1 - y0)),
            "quad": ",".join("%d" % round(v) for v in quad.reshape(-1)),
            "is_vehicle": p["is_vehicle"], "is_synthetic": 1,
            "source": "synthetic (generate_synthetic.py)", "license": "CC-BY-4.0 (generated by the participant)",
            "conditions": ",".join(p["conditions"]),
        })
    with open(os.path.join(out, "labels", name + ".txt"), "w") as f:
        f.write("\n".join(lab) + ("\n" if lab else ""))
    return idx, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="..", help="корень датасета")
    ap.add_argument("--n", type=int, default=5000)
    ap.add_argument("--start", type=int, default=0)
    ap.add_argument("--seed", type=int, default=20261014)
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--meta", default=None, help="куда писать meta (по умолчанию <out>/meta_synthetic.csv)")
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "images", "synthetic"), exist_ok=True)
    os.makedirs(os.path.join(a.out, "labels"), exist_ok=True)
    jobs = [(i, a.seed, a.out) for i in range(a.start, a.start + a.n)]
    meta_path = a.meta or os.path.join(a.out, "meta_synthetic.csv")
    with open(meta_path, "w", newline="", encoding="utf-8") as f, Pool(a.workers) as pool:
        w = csv.DictWriter(f, fieldnames=META_FIELDS, delimiter=";")
        w.writeheader()
        for k, (idx, rows) in enumerate(pool.imap(build_one, jobs, chunksize=8)):
            w.writerows(rows)
            if k % 500 == 0:
                print(f"{k}/{a.n}", flush=True)


if __name__ == "__main__":
    main()
